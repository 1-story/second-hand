-- ============================================================
-- updated_at 触发器（所有含 updated_at 的表）
-- ============================================================
CREATE TRIGGER trg_user_updated_at      BEFORE UPDATE ON "user"          FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_category_updated_at  BEFORE UPDATE ON category        FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_product_updated_at   BEFORE UPDATE ON product         FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_order_updated_at     BEFORE UPDATE ON trade_order     FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_credit_updated_at    BEFORE UPDATE ON carbon_credit   FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_draft_updated_at     BEFORE UPDATE ON ai_publish_draft FOR EACH ROW EXECUTE FUNCTION set_updated_at();

