-- 约定：主键 BIGINT IDENTITY；逻辑删除 deleted SMALLINT(0/1)；金额 DECIMAL(10,2)
-- 说明：updated_at 自动更新由统一触发器维护；中文检索使用 pg_trgm + ILIKE（业务层兜底）
-- ============================================================

CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- ============================================================
-- 统一 updated_at 自动更新触发器
-- ============================================================
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

